/** Fixed-Λ enumeration engine for the Krotenheerdt tilings (OEIS A068600), the scalable replacement for the
  * patch-growth search (ADR-0018). Instead of growing aperiodic patches and rejecting them at certification,
  * it enumerates candidate translation lattices Λ from a bounded set and, for each fixed Λ, grows only
  * Λ-consistent patches ([[LatticeConsistency]]): off-lattice "decoration" placements are pruned at the
  * branch point, so the scatter is never built. The per-Λ search is tiny, so the cost scales to higher n.
  *
  * Each fixed-Λ patch that tiles one fundamental cell is verified directly on the torus ([[verifyTorus]]):
  * distinct faces tile one covolume, every torus vertex has a complete 360° fan, and vertex orbits (color
  * refinement of the torus vertex graph) and types both equal n. Completeness rests on the candidate set
  * including every true lattice: the vertices of a regular-polygon tiling lie in the module ℤ[ζ₁₂] (30°
  * directions, plus ℤ[ζ₈] 45° directions for the octagon's 4.8.8), and every translation period is itself
  * such a vector, so a step-bounded enumeration of that module — with the bound k verified per n by
  * reproducing the published count — contains them all.
  *
  * STATUS (WIP, see ADR-0019): the torus-native verification is the performance breakthrough (n=1 small cells
  * ~2s vs. the planar approach's timeout) and is correct for single-vertex-cell tilings (3⁶, 4⁴, 3³.4²).
  * Multi-vertex-cell tilings (e.g. 6.6.6) are not yet found — [[verifyTorus]] needs every torus vertex
  * completed (more growth than the current cap) and the torus-vertex grouping needs rounding-hardening. Not
  * yet validated against the published n=1..3 counts. The original [[KrotenheerdtSearch]] remains the
  * reference engine that rigorously enumerated n ≤ 2.
  */
object KrotenheerdtLatticeSearch:

  final case class Outcome(
      tilings: List[(Set[VertexSignature], String)],
      basesTried: Int,
      statesExplored: Long
  )

  // Candidate lattices are enumerated in Double — exact BigDecimal arithmetic on arbitrary module points
  // makes Gauss reduction explode in precision and hang; the candidates only need ~1e-12 accuracy (the
  // oracle and verifyTorus recompute everything precisely at SCALE 9), so Double is both correct and fast.
  private type P = (Double, Double)

  /** Unit vectors at multiples of `step` degrees. */
  private def unit(stepDegrees: Int): P =
    val r = math.toRadians(stepDegrees)
    (math.cos(r), math.sin(r))

  // ℤ[ζ₁₂] is generated by unit steps at 0,30,60,90°; ℤ[ζ₈] (octagon) by 0,45,90,135°.
  private val generators12 = List(0, 30, 60, 90).map(unit)
  private val generators8  = List(0, 45, 90, 135).map(unit)

  private def dot(a: P, b: P): Double   = a._1 * b._1 + a._2 * b._2
  private def cross(a: P, b: P): Double = a._1 * b._2 - a._2 * b._1
  private def keyD(p: P): (Long, Long)  = (math.round(p._1 * 1e6), math.round(p._2 * 1e6))
  private def neg(p: P): P              = (-p._1, -p._2)
  private def canonicalSign(p: P): P    =
    if p._2 > 1e-9 || (math.abs(p._2) <= 1e-9 && p._1 > 0) then p else neg(p)

  /** Lagrange–Gauss reduction of a 2D basis to the two successive minima. Stops when `b` is reduced against
    * `a` (2|a·b| ≤ |a|²); the strict-plus-epsilon condition keeps equal-length 60° pairs (where `round(0.5)`
    * would otherwise over-reduce and oscillate) from looping, and an iteration cap is a float safety net.
    */
  private def gaussReduceD(v0: P, w0: P): (P, P) =
    var a    = v0
    var b    = w0
    if dot(a, a) > dot(b, b) then { val t = a; a = b; b = t }
    var iter = 0
    while iter < 10_000 && 2 * math.abs(dot(a, b)) > dot(a, a) + 1e-9 do
      val m = math.round(dot(a, b) / dot(a, a)).toDouble
      b = (b._1 - m * a._1, b._2 - m * a._2)
      if dot(a, a) > dot(b, b) then { val t = a; a = b; b = t }
      iter += 1
    (a, b)

  /** Module points reachable within integer step-count `k` over the given generators (and their negatives).
    */
  private def modulePoints(generators: List[P], k: Int): List[P] =
    val seen                                              = mutable.LinkedHashMap.empty[(Long, Long), P]
    def go(remaining: List[P], budget: Int, acc: P): Unit =
      remaining match
        case Nil     => seen.getOrElseUpdate(keyD(acc), acc)
        case g :: gs =>
          for c <- -budget to budget do go(gs, budget - math.abs(c), (acc._1 + c * g._1, acc._2 + c * g._2))
    go(generators, k, (0.0, 0.0))
    seen.values.toList

  /** A fundamental cell holds at least one polygon, so its covolume is at least the smallest face area (a
    * unit triangle, √3/4 ≈ 0.433). The dense rank-4 module otherwise yields infinitely many spurious
    * tiny-covolume lattices; this floor removes them. The ceiling bounds the largest cell to enumerate.
    */
  private val minCovolume = 0.4

  // Unit-edge polygon areas {3,4,6,8,12}. A fundamental cell is a whole number of polygons, so its covolume
  // is a non-negative integer combination of these — a sparse set. Filtering candidate covolumes to it drops
  // the dense module's spurious lattices (whose covolume is an arbitrary real) by a large factor.
  private val polygonAreas = List(3, 4, 6, 8, 12).map(s => s / (4.0 * math.tan(math.Pi / s)))

  private def achievableCovolumes(maxCovolume: Double): Set[Double] =
    val reached  = mutable.Set(0.0)
    var frontier = List(0.0)
    while frontier.nonEmpty do
      frontier = frontier.flatMap: c =>
        polygonAreas.map(c + _).filter(s => s <= maxCovolume + 1e-6 && reached.add(s))
    reached.filter(_ >= minCovolume - 1e-6).toSet

  private def isAchievable(covol: Double, achievable: Set[Double]): Boolean =
    achievable.exists(a => math.abs(a - covol) < 1e-6)

  /** Candidate primitive bases within step bound `k` and covolume in `[minCovolume, maxCovolume]`, Gauss-
    * reduced, sign-canonicalised, deduped, ordered by covolume (smallest fundamental cell first). Includes
    * the octagon (45°) module when `withOctagon`.
    */
  def candidateBases(k: Int, maxCovolume: Double, withOctagon: Boolean = false): List[(BigPoint, BigPoint)] =
    val achievable = achievableCovolumes(maxCovolume)
    val points     =
      (modulePoints(generators12, k) ++ (if withOctagon then modulePoints(generators8, k) else Nil))
        .filter(p => math.hypot(p._1, p._2) > 1e-6)
    val byKey      = mutable.LinkedHashMap.empty[((Long, Long), (Long, Long)), (P, P)]
    for
      i   <- points.indices
      j   <- (i + 1) until points.size
      area = math.abs(cross(points(i), points(j)))
      if area >= minCovolume && area <= maxCovolume + 1e-9
    do
      val (a, b) = gaussReduceD(points(i), points(j))
      val cov    = math.abs(cross(a, b))
      if cov >= minCovolume - 1e-9 && cov <= maxCovolume + 1e-9 && isAchievable(cov, achievable) then
        val (ca, cb) = (canonicalSign(a), canonicalSign(b))
        val ord      = Ordering[(Double, (Long, Long))]
        val pair     =
          if ord.lteq((dot(ca, ca), keyD(ca)), (dot(cb, cb), keyD(cb))) then (ca, cb) else (cb, ca)
        byKey.getOrElseUpdate((keyD(pair._1), keyD(pair._2)), pair)
    byKey.values.toList
      .sortBy((v, w) => (math.abs(cross(v, w)), dot(v, v) + dot(w, w)))
      .map((v, w) =>
        (BigPoint(BigDecimal(v._1), BigDecimal(v._2)), BigPoint(BigDecimal(w._1), BigDecimal(w._2)))
      )

  /** Enumerate all Krotenheerdt n-uniform tilings via fixed-Λ growth over candidate bases up to step bound k.
    */
  def enumerate(
      n: Int,
      k: Int,
      maxCovolume: Double,
      parallelism: Int = 1,
      log: String => Unit = _ => ()
  ): Outcome =
    import java.util.concurrent.ConcurrentHashMap
    import java.util.concurrent.atomic.AtomicLong
    import scala.jdk.CollectionConverters.*

    val bases  = candidateBases(k, maxCovolume, withOctagon = n == 1)
    val found  = new ConcurrentHashMap[String, Set[VertexSignature]]()
    val states = new AtomicLong(0)
    val done   = new AtomicLong(0)
    val capped = new AtomicLong(0)
    val perCap = 400
    log(s"n=$n k=$k maxCovol=$maxCovolume: ${bases.size} candidate lattices")

    def runLattice(v: BigPoint, w: BigPoint): Unit =
      val covol   = v.cross(w).abs
      val visited = mutable.HashSet.empty[List[(Int, BigDecimal, BigDecimal)]]
      val stack   = mutable.Stack.empty[Tiling]
      var local   = 0
      polygonSides.foreach: sides =>
        val seed = TilingBuilder.createRegularPolygon(RegularPolygon(sides))
        if LatticeConsistency.isConsistent(seed, v, w, seed.vertices.head.coords) then stack.push(seed)
      while stack.nonEmpty && local < perCap do
        val patch  = stack.pop()
        states.incrementAndGet()
        local += 1
        val origin = patch.vertices.head.coords
        val area   = patch.innerFaces.map(_.areaUnsafe).sum
        // Grow only until the patch's distinct torus faces tile ONE fundamental cell, so the patch stays ~1
        // cell (small) — no large planar growth. Then replicate it to a block by lattice translation (cheap,
        // and the merge validates periodicity) and hand that to the existing certify for orbit count, types
        // and the canonical key. The cheap area test gates the expensive torus-area scan.
        // Verify once the patch's distinct faces tile a cell; verifyTorus also needs every torus vertex to
        // have a complete (interior) instance, which takes ~1.5 cells, so keep growing until it succeeds or
        // the patch is clearly too big (3 cells).
        if area >= covol - 1e-6 && distinctTorusFaceArea(patch, v, w, origin) >= covol - 1e-6 then
          verifyTorus(patch, v, w, origin, n) match
            case Some((types, key)) => found.putIfAbsent(key, types): Unit
            case None               => if area < covol * 9 then grow(patch, v, w, origin, n, visited, stack)
        else if area < covol * 9 then grow(patch, v, w, origin, n, visited, stack)
      if local >= perCap then capped.incrementAndGet()
      val d       = done.incrementAndGet()
      if d % 50 == 0 then
        log(s"  lattices ${d}/${bases.size}, states=${states.get}, found=${found.size}, capped=${capped.get}")

    if parallelism <= 1 then bases.foreach(runLattice)
    else
      val pool = java.util.concurrent.Executors.newFixedThreadPool(parallelism)
      try bases.foreach((v, w) => pool.submit(new Runnable { def run(): Unit = runLattice(v, w) }))
      finally
        pool.shutdown()
        pool.awaitTermination(7, java.util.concurrent.TimeUnit.DAYS)
    log(s"  capped lattices (hit ${perCap} states): ${capped.get}")

    Outcome(found.asScala.toList.map((key, types) => (types, key)).sortBy(_._2), bases.size, states.get)

  private def fracOf(x: BigDecimal): BigDecimal =
    val r = x.setScale(9, BigDecimal.RoundingMode.HALF_UP)
    val f = r - r.setScale(0, BigDecimal.RoundingMode.FLOOR)
    if f >= BigDecimal(1) then BigDecimal(0).setScale(9) else f.setScale(9, BigDecimal.RoundingMode.HALF_UP)

  /** Total area of the patch's inner faces taken once per torus position (size, centroid mod Λ). Equals one
    * covolume exactly when the patch covers a full fundamental cell of distinct faces.
    */
  private def distinctTorusFaceArea(
      patch: TilingDCEL,
      v: BigPoint,
      w: BigPoint,
      origin: BigPoint
  ): BigDecimal =
    val det = v.x * w.y - v.y * w.x
    patch.innerFaces
      .map: f =>
        val c = f.getVerticesUnsafe.map(_.coords).centroid
        val d = c - origin
        (
          (
            f.halfEdgesUnsafe.size,
            fracOf((d.x * w.y - w.x * d.y) / det),
            fracOf((v.x * d.y - d.x * v.y) / det)
          ),
          f.areaUnsafe
        )
      .distinctBy(_._1)
      .map(_._2)
      .sum

  /** Torus-native verification of a one-cell Λ-consistent patch, replacing the expensive planar replicate +
    * certify. Returns the canonical torus key and the vertex-type set when the patch is a valid Krotenheerdt
    * tiling: the distinct torus faces tile one cell, every torus vertex has a complete 360° valid fan, and
    * the vertex orbits (color refinement of the torus vertex graph) number exactly n with n distinct types.
    */
  private[dcel] def verifyTorus(
      patch: TilingDCEL,
      v: BigPoint,
      w: BigPoint,
      origin: BigPoint,
      n: Int
  ): Option[(Set[VertexSignature], String)] =
    val det                                         = v.x * w.y - v.y * w.x
    def tkey(p: BigPoint): (BigDecimal, BigDecimal) =
      val d = p - origin
      (fracOf((d.x * w.y - w.x * d.y) / det), fracOf((v.x * d.y - d.x * v.y) / det))

    // Torus vertices: group planar vertices by position mod Λ; each must have an interior (complete) instance.
    val byTorus  = patch.vertices.groupBy(vertex => tkey(vertex.coords))
    val complete =
      byTorus.view.mapValues(_.find(_.currentInteriorAngleSumUnsafe(patch.outerFace) ==
        AngleDegree(360))).toMap
    if sys.props.contains("krot.vdbg") then
      println(s"  [vdbg] torusVerts=${byTorus.size} incomplete=${complete.count(
          _._2.isEmpty
        )} types=${complete.collect { case (k, Some(vx)) => vertexTypeOf(patch, vx).mkString(".") }.toSet}")
    if complete.values.exists(_.isEmpty) then None
    else
      val reps  = complete.view.mapValues(_.get).toMap
      val types = reps.values.map(vertexTypeOf(patch, _)).toSet
      if types.sizeIs != n then None
      else
        // Torus-vertex adjacency with edge labels (the two incident face sizes), for color refinement.
        def faceSize(f: Option[structure.Face]): Int =
          f.filter(_ != patch.outerFace).map(_.halfEdgesUnsafe.size).getOrElse(0)
        val adj                                      = reps.map: (tk, vertex) =>
          tk -> vertex.incidentEdgesUnsafe.map: e =>
            val label = List(faceSize(e.incidentFace), faceSize(e.twin.flatMap(_.incidentFace))).sorted
            (tkey(e.destinationUnsafe.coords), label)
        var color                                    = reps.map((tk, vtx) => tk -> vertexTypeOf(patch, vtx).mkString(".")).toMap
        var stable                                   = false
        while !stable do
          val next = adj.map: (tk, ns) =>
            tk ->
              (color(tk) + "|" +
                ns.map((nk, lbl) => (lbl.mkString, color.getOrElse(nk, ""))).sorted.mkString(","))
          stable = next.values.toSet.size == color.values.toSet.size
          color = next
        val orbits                                   = color.values.toSet.size
        if orbits != n then None
        else
          // Canonical torus key: faces (size, pos mod Λ) and typed vertices, lex-min over basis re-expressions
          // and cell origins. Reuses the existing torusKey machinery via a synthetic single-cell block.
          val faces = patch.innerFaces
            .map(f => (f.halfEdgesUnsafe.size, f.getVerticesUnsafe.map(_.coords).centroid))
            .distinctBy((s, c) => (s, tkey(c)))
          Some((
            types,
            torusContentKey(
              v,
              w,
              origin,
              faces,
              reps.values.toList.map(vtx => (vertexTypeOf(patch, vtx).mkString("."), vtx.coords))
            )
          ))

  /** Reduce a basis to the primitive cell: if the face content (in lattice coordinates) is invariant under a
    * half-period shift, the cell is a multiple of the true one — halve and repeat. Without this, the same
    * tiling found under a sublattice (doubled cell) gets a different key than under its primitive cell.
    */
  private def primitiveBasis(
      v0: BigPoint,
      w0: BigPoint,
      origin: BigPoint,
      faces: List[(Int, BigPoint)]
  ): (BigPoint, BigPoint) =
    def reduce(v: BigPoint, w: BigPoint): (BigPoint, BigPoint) =
      val det                                     = v.x * w.y - v.y * w.x
      def lat(p: BigPoint)                        =
        val d = p - origin
        ((d.x * w.y - w.x * d.y) / det, (v.x * d.y - d.x * v.y) / det)
      val content                                 = faces.map((s, c) => (s, lat(c)))
      def shifted(sa: BigDecimal, sb: BigDecimal) =
        content.map((s, ab) => (s, fracOf(ab._1 + sa), fracOf(ab._2 + sb))).toSet
      val base                                    = shifted(0, 0)
      val half                                    = BigDecimal("0.5")
      if shifted(half, 0) == base then reduce(v.scaled(half), w)
      else if shifted(0, half) == base then reduce(v, w.scaled(half))
      else if shifted(half, half) == base then reduce(v, (v + w).scaled(half))
      else (v, w)
    reduce(v0, w0)

  /** Canonical key of one fundamental cell's content under all equivalent bases and cell origins. */
  private def torusContentKey(
      v00: BigPoint,
      w00: BigPoint,
      origin: BigPoint,
      faces: List[(Int, BigPoint)],
      verts: List[(String, BigPoint)]
  ): String =
    val (v, w)     = primitiveBasis(v00, w00, origin, faces)
    val candidates = List(v, w, v + w, v - w).flatMap(p => List(p, BigPoint.origin - p))
    val det0       = (v.x * w.y - v.y * w.x).abs
    val keys       =
      for
        a  <- candidates
        b  <- candidates
        det = a.x * b.y - a.y * b.x
        if (det.abs - det0).abs < BigDecimal("1e-9")
      yield
        def lat(p: BigPoint): (BigDecimal, BigDecimal) =
          val d = p - origin
          ((d.x * b.y - b.x * d.y) / det, (a.x * d.y - d.x * a.y) / det)
        val fs                                         = faces.map((s, c) => (s, lat(c)))
        val vs                                         = verts.map((t, c) => (t, lat(c)))
        fs.map(_._2).distinct.map: (oa, ob) =>
          val f = fs.map((s, ab) => (s, fracOf(ab._1 - oa), fracOf(ab._2 - ob))).distinct.sorted
          val u = vs.map((t, ab) => (t, fracOf(ab._1 - oa), fracOf(ab._2 - ob))).distinct.sorted
          (f.map((s, x, y) => s"$s:$x:$y") ++ u.map((t, x, y) => s"$t:$x:$y")).mkString("|")
        .min
    keys.min

  /** Push every Λ-consistent, sound continuation that fills the centroid-nearest boundary gap. */
  private def grow(
      patch: Tiling,
      v: BigPoint,
      w: BigPoint,
      origin: BigPoint,
      n: Int,
      visited: mutable.HashSet[List[(Int, BigDecimal, BigDecimal)]],
      stack: mutable.Stack[Tiling]
  ): Unit =
    val gaps     = patch.boundaryVerticesUnsafe.flatMap: vertex =>
      val gap = AngleDegree(360) - vertex.currentInteriorAngleSumUnsafe(patch.outerFace)
      Option.when(gap.toRational > 0)((vertex, gap))
    val centroid = patch.vertices.map(_.coords).centroid
    gaps.minByOption((vertex, gap) =>
      (vertex.coords.distanceTo(centroid), gap.toRational, vertex.id.value)
    ).foreach: (target, gap) =>
      val previousInnerIds = patch.innerVertices.map(_.id).toSet
      polygonSides.foreach: sides =>
        if interiorAngle(sides).toRational <= gap.toRational then
          patch
            .maybeAddRegularPolygonToBoundary(target.id, RegularPolygon(sides))
            .toOption
            .filter(next =>
              isSound(next, previousInnerIds, n) && LatticeConsistency.isConsistent(next, v, w, origin)
            )
            .foreach: next =>
              if visited.add(PatchCanonical.congruenceKey(next)) then stack.push(next)

  private def isSound(next: Tiling, previousInnerIds: Set[structure.VertexId], n: Int): Boolean =
    val newInnerValid =
      next.innerVertices
        .filterNot(v => previousInnerIds.contains(v.id))
        .forall(v => isCompleteVertex(vertexTypeOf(next, v)))
    val fansValid     =
      next.boundaryVerticesUnsafe.forall: vertex =>
        boundaryFan(next, vertex) match
          case Nil => true
          case fan => isExtendableFan(fan)
    next.hasUnitRegularPolygonsOnly && newInnerValid && fansValid && innerVertexTypes(next).sizeIs <= n

  private def boundaryFan(tiling: TilingDCEL, vertex: structure.Vertex): List[Int] =
    val edges      = vertex.incidentEdgesUnsafe
    val outerIndex = edges.indexWhere(_.incidentFace.exists(_ eq tiling.outerFace))
    val ordered    = if outerIndex < 0 then edges else edges.startAt(outerIndex).tail
    ordered.flatMap(_.incidentFace).filter(_ != tiling.outerFace).map(_.halfEdgesUnsafe.size)
